class SenateXml(unittest.TestCase):
    def test_parse_and_code(self):
        meta, members = senate_votes.parse_vote_xml(XML)
        self.assertEqual((meta["congress"], meta["session"], meta["roll"]), (119, 2, 80))
        self.assertEqual((meta["yeas"], meta["nays"]), (40, 59))
        people = {"S000033": {"id": {"lis": "S313"}}, "P000603": {"id": {"lis": "S348"}}}
        coded = senate_votes.code_votes(members, senate_votes.lis_to_bioguide(people)).set_index("lis_id")
        self.assertEqual(coded.loc["S313", "bioguide_id"], "S000033")
        self.assertEqual(coded.loc["S313", "yea"], 1.0)
        self.assertEqual(coded.loc["S348", "yea"], 0.0)
        self.assertTrue(np.isnan(coded.loc["S423", "yea"]))

    def test_url_pattern(self):
        url = senate_votes.VOTE_URL.format(congress=119, session=2, roll=80)
        self.assertTrue(url.endswith("vote1192/vote_119_2_00080.xml"))


def synthetic(beta, gamma=0.0, n_items=12, families=3, two_presidents=False, seed=0):
    """Simulate a Senate voting on items generated by a known mapping."""
    rng = np.random.default_rng(seed)
    n = 100
    party = np.array(["D"] * 50 + ["R"] * 50)
    d1 = np.where(party == "D", rng.normal(-0.35, 0.15, n), rng.normal(0.5, 0.15, n))
    d2 = rng.normal(0, 0.3, n)
    u = rng.normal(0, 0.3, n)
    sen = pd.DataFrame({"bioguide_id": [f"S{i}" for i in range(n)], "party": party,
                        "nominate_dim1": d1, "nominate_dim2": d2})
    items, votes = [], []
    for j in range(n_items):
        pres = "D" if (two_presidents and j % 2) else "R"
        alpha = rng.normal(0, 0.6)
        item_id = f"119-1-{j}"
        items.append({"item_id": item_id, "dimension": "dim", "plus_side": "Yea",
                      "family": f"f{j % families}", "president_party": pres})
        cp = (party == pres).astype(float)
        eta = alpha + beta[0] * d1 + beta[1] * d1 ** 2 + beta[2] * d2 + gamma * cp + u
        y = (rng.random(n) < norm.cdf(eta)).astype(float)
        votes.append(pd.DataFrame({"item_id": item_id, "bioguide_id": sen["bioguide_id"],
                                   "party": party, "vote_cast": "", "yea": y}))
    return (pd.DataFrame(items), pd.concat(votes, ignore_index=True),
            sen[["bioguide_id", "nominate_dim1", "nominate_dim2"]])


class Fitter(unittest.TestCase):
    def roster(self, ideo):
        return ideo.rename(columns={"nominate_dim1": "d1", "nominate_dim2": "d2"})[["d1", "d2"]]

    def test_recovers_u_shape(self):
        # Defense-like: support peaks near the centre-right and falls at both ends.
        items, votes, ideo = synthetic(beta=(2.0, -4.0, 0.0), n_items=20, seed=1)
        data = calibration.build_dataset(items, votes, ideo)
        fit = calibration.fit_dimension(data, "dim", self.roster(ideo))
        self.assertLess(fit.beta["d1_sq"], -1.0)
        peak = -fit.beta["d1"] / (2 * fit.beta["d1_sq"])
        self.assertAlmostEqual(peak, 0.25, delta=0.25)
        self.assertFalse(fit.gamma_identified)

    def test_gamma_identified_with_two_presidents(self):
        items, votes, ideo = synthetic(beta=(-2.0, 0.0, 0.0), gamma=-1.0, n_items=24,
                                       two_presidents=True, seed=2)
        data = calibration.build_dataset(items, votes, ideo)
        fit = calibration.fit_dimension(data, "dim", self.roster(ideo))
        self.assertTrue(fit.gamma_identified)
        self.assertLess(fit.gamma, -0.4)
        self.assertLess(fit.beta["d1"], -1.0)

    def test_plus_side_nay_flips_direction(self):
        items, votes, ideo = synthetic(beta=(2.0, 0.0, 0.0), seed=3)
        items["plus_side"] = "Nay"
        data = calibration.build_dataset(items, votes, ideo)
        fit = calibration.fit_dimension(data, "dim", self.roster(ideo))
        self.assertLess(fit.beta["d1"], 0)

    def test_lopsided_items_dropped(self):
        items, votes, ideo = synthetic(beta=(2.0, 0.0, 0.0), seed=4)
        votes.loc[votes["item_id"] == "119-1-0", "yea"] = 1.0
        votes.loc[(votes["item_id"] == "119-1-0") & (votes["bioguide_id"] == "S0"), "yea"] = 0.0
        data = calibration.build_dataset(items, votes, ideo)
        fit = calibration.fit_dimension(data, "dim", self.roster(ideo))
        self.assertNotIn("119-1-0", fit.items["item_id"].tolist())

    def test_deviant_senator_flagged(self):
        items, votes, ideo = synthetic(beta=(-2.5, 0.0, 0.0), n_items=20, seed=5)
        # A liberal senator who always votes on the -2 side, like Fetterman on arms sales.
        liberal = ideo.sort_values("nominate_dim1")["bioguide_id"].iloc[0]
        votes.loc[votes["bioguide_id"] == liberal, "yea"] = 0.0
        data = calibration.build_dataset(items, votes, ideo)
        fit = calibration.fit_dimension(data, "dim", self.roster(ideo))
        row = fit.deviations.set_index("bioguide_id").loc[liberal]
        self.assertLess(row["u_raw_score"], -0.75)
        self.assertLess(row["u_score"], 0)
        self.assertTrue(row["suggest_override"])
        self.assertGreater(fit.cv["within_party_accuracy"], 0.5)

    def test_consistency_flags_contradiction_and_override_resolves_it(self):
        items, votes, ideo = synthetic(beta=(-2.5, 0.0, 0.0), n_items=20, seed=8)
        liberal = ideo.sort_values("nominate_dim1")["bioguide_id"].iloc[0]
        votes.loc[votes["bioguide_id"] == liberal, "yea"] = 0.0
        data = calibration.build_dataset(items, votes, ideo)
        fit = calibration.fit_dimension(data, "dim", self.roster(ideo))
        none = calibration.consistency(data, fit, {}).set_index("bioguide_id")
        self.assertTrue(none.loc[liberal, "contradiction"])
        fixed = calibration.consistency(data, fit, {liberal: -2.0}).set_index("bioguide_id")
        self.assertFalse(fixed.loc[liberal, "contradiction"])
        self.assertTrue(fixed.loc[liberal, "has_override"])

    def test_two_outliers_do_not_bend_a_thin_dimension(self):
        # Defense-like: support rises with d1; six near-replicate items from one bill.
        # The two most conservative senators always vote Nay (like Paul and Lee).
        items, votes, ideo = synthetic(beta=(3.0, 0.0, 0.0), n_items=6, families=1, seed=7)
        right = ideo.sort_values("nominate_dim1")["bioguide_id"].iloc[-2:].tolist()
        votes.loc[votes["bioguide_id"].isin(right), "yea"] = 0.0
        data = calibration.build_dataset(items, votes, ideo)
        fit = calibration.fit_dimension(data, "dim", self.roster(ideo))
        self.assertTrue(fit.thin)
        self.assertGreater(fit.beta["d1_sq"], -1.0)
        dev = fit.deviations.set_index("bioguide_id")
        self.assertTrue((dev.loc[right, "u_raw_score"] < 0).all())
        # A conservative who voted with the mapping still scores well above the median.
        r = self.roster(ideo).assign(d1_sq=lambda d: d["d1"] ** 2)
        third = ideo.sort_values("nominate_dim1").iloc[-3]
        score = calibration.latent_to_score(third["nominate_dim1"], third["nominate_dim2"], fit.to_dict())
        self.assertGreater(score, 0.5)

    def test_engine_uses_fit_and_round_trips(self):
        items, votes, ideo = synthetic(beta=(2.0, 0.0, 0.0), seed=6)
        items["dimension"] = "defense_budget"
        data = calibration.build_dataset(items, votes, ideo)
        fit = calibration.fit_dimension(data, "defense_budget", self.roster(ideo))
        tmp = Path(self._tmp()) / "fp.json"
        calibration.save([fit], tmp, {"test": True})
        loaded = calibration.load(tmp)
        bl = pd.DataFrame({"bioguide_id": ["A", "B", "C"], "name": list("ABC"), "state": ["MA", "WY", "VT"],
                           "caucus": ["D", "R", "D"], "nominate_dim1": [-0.4, 0.6, None],
                           "nominate_dim2": [0.0, 0.0, None], "score_chamber": ["Senate", "House", None]})
        mod = foreign_policy.MODULE
        from dataclasses import replace
        mod = replace(mod, override_path=Path(self._tmp()) / "none.csv")
        out = base.score(bl, mod, loaded).set_index("bioguide_id")
        self.assertEqual(out.loc["A", "defense_budget_source"], "fitted")
        self.assertEqual(out.loc["C", "defense_budget_source"], "imputed")
        self.assertLess(out.loc["A", "defense_budget"], out.loc["B", "defense_budget"])
        self.assertGreater(out.loc["B", "defense_budget_sd"], out.loc["A", "defense_budget_sd"])
        # China is never calibrated and keeps its widened prior SD.
        self.assertEqual(out.loc["A", "china_decoupling_source"], "formula")
        self.assertGreaterEqual(out.loc["A", "china_decoupling_sd"], 0.6)

    def _tmp(self):
        import tempfile
        return tempfile.mkdtemp()


class CalibrationItemsFile(unittest.TestCase):
    def test_items_file_well_formed(self):
        path = Path(__file__).resolve().parents[1] / "data" / "manual" / "calibration_votes.csv"
        items = pd.read_csv(path)
        dims = {d.name for d in foreign_policy.MODULE.dimensions if d.calibrate}
        self.assertTrue(set(items["dimension"]) <= dims)
        self.assertTrue(items["plus_side"].isin(["Yea", "Nay"]).all())
        self.assertTrue(items["president_party"].isin(["D", "R"]).all())
        self.assertFalse(items.duplicated(["congress", "session", "roll"]).any())
        self.assertNotIn("china_decoupling", set(items["dimension"]))


